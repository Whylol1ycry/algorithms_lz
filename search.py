import random
size = 100 #устанавливаем размер списка
spisok = random.sample(range(0, 1000000), size) #прописываем наш список и команду сэмпл чтобы искольчить дубликаты
spisok.sort() #командой сорт сортируем список по возрастанию
chislo = random.choice(spisok) #выбираем рандомное число из списка которое нужно найти
print("Список:", spisok) #выводим список
print("Ищем число:", chislo) #выводим число которое нужно найти
# Линейный поиск
lineyka_sravn = 0 #добавляем счётчик инверсий
lineyka_idx = -1 #добавляем счётчик индекса -1 потому что счёт индексов начинается с 0 и это даст нам правильный ответ в следующей операции в цикле

for i in range(size): #создаём цикл размером со список, потому что число наших чисел равно длине списка
    lineyka_sravn = lineyka_sravn + 1 #пишем прибавлять единичку после каждого сравнения
    if spisok[i] == chislo: #если какое то число при перебирании совпало с искомым то:
        lineyka_idx = i #пишем индекс этого числа, которое совпало
        break #останавлиаем цикл поиска

# Бинарный поиск
binarny_sravn = 0 #вводим счётчик сравнений
binarny_idx = -1 #вводим счётчик индекса
left = 0 #создаём левую границу нашего списка и ложим в эту переменную значение индекса самого первого числа списка тоесть 0
right = size - 1 #создаём правую границу нашего списка и ложим в эту переменную значение индекса самого последнего число тоесть сайз - 1 так как счёт индексов начинается с 0
while left <= right: # создаёс условия для цикла который будет работать пока левая граница не перешагнёт правую
    binarny_sravn = binarny_sravn + 1 #добавляем единицу каждый раз в счётчик сравнений
    mid = (left + right) // 2 #находим индекс элемента который находится посередине
    
    if spisok[mid] == chislo: #проверяет, а может то число по середине и есть искомое число?
        binarny_idx = mid #если да то записываем индекс середины и брейкаем на аолгоритм тк задача выполнена
        break
    
    if spisok[mid] < chislo:# если середина меньше середины
        left = mid + 1#то сдвигаем левую границу на место мид+1 потому что если середина меньше этого числа, то все числа меньше середины можно отюросить
    else:
        right = mid - 1#в случае если середина больше числа, то мы сдвигаем правую границу на место м-1, потому что если середина больше этого числа, то числа большее середины можно отбросить

print("Линейный поиск — Индекс:", lineyka_idx, "Сравнений:", lineyka_sravn)#выводим нужыне результаты по линейному поиску
print("Бинарный поиск — Индекс:", binarny_idx, "Сравнений:", binarny_sravn)#выводим нужные результаты по бинарному поиску
if lineyka_idx == -1 and binarny_idx == -1:#добавляем ещё один цикл иф который будет на случай если ни один поиск не помог
    print("Элемент не найден.")#выводим тогда соответствующее сообщение