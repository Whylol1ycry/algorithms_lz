import random
#Сортировка пузырьком
size = 100 #устанавливаем размер списка
spisok = []#делаем пока что пустой список 
for i in range(size):#обозначаем действие цикла в границах длины списка 
    chislo = random.randint(0, 100)#выбираем рандомное число я написал от 0 до 100 потому что тут это удобнее
    spisok.append(chislo)#пишем добавить это число в наш список
print (spisok)#прописал список посмотреть как выглядит
schet = 0  #вводим счёт сравнений
for i in range(size):#обозначаем действие цикла в границах длины списка
    for j in range(size - 1):#для j прописываем сайз минус 1 потому что он отвечает за индекс а индексация начинается с 0
        schet = schet + 1#прибавляем по 1 после каждого сравнения
        if spisok[j] < spisok[j+1]:#сравниваем два соседних элемента 
            swapchik = spisok[j]#создаём переменную-коробку куда ложим элемент
            spisok[j] = spisok [j+1]#переносим большее число которое нам нужно на место меньше и теперь у нас два таких больших числа на позициях
            spisok[j+1] = swapchik#даём большему значению переменную коробочку в которой лежал меньший и теперь всё правильно, больший встал на место меньшего, а меньший на место большего
            print("Пузырёк шаг", i + 1, spisok)#выводим каждый такой шаг перемены мест
#Сортировка выбором          
spisok2 = spisok.copy()#создаём второй список и копируем всё из предыдущего
schet2 = 0#вводим счётчик сравнений
for i in range(size):#обозначаем действие цикла в границах длины списка 
    max_index = i#назначаем элемент под номером и самым большим
    for j in range(i + 1, size):#запускаем цикл который смотрит на оставшиеся числа и начинаем со следующего после и
        schet2 = schet2 + 1 # Счетчик сравнений 
        if spisok2[j] > spisok2[max_index]:#если какой то элемент с индексом j больше нашего максимального
            max_index = j#то даём ему максимальный индекс и через знакомый способ ставим на место прошлого самого большего
    swapchik = spisok2[i]#бросаем элемент с индексом и в переменную коробку
    spisok2[i] = spisok2[max_index]#переносим большее число
    spisok2[max_index] = swapchik#и окончательно ставим большее число на место выравнивая порядок и исключая раздвоения
    print("Выбор шаг", i + 1, spisok2)#каждое изменение помечаем и выводим
print("Отсортированный список:", spisok)#выводим отсортированный список
print("Сравнений в пузырьке:", schet)#выводим счёт сравнений в пузырьке
print("Сравнений в выборе:", schet2)#выводим счёт сравнений в выборе